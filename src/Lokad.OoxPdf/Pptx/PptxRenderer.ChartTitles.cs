    private static async ValueTask RenderChartTitleAsync(PptxDocument document, PptxTheme theme, PptxColorMap colorMap, PdfGraphicsBuilder graphics, ShapeBounds bounds, XDocument chartXml, PptxSceneChart sceneChart, ChartWorkbookData? workbook, bool plotVisibleOnly, PresentationFontResolver fontResolver, List<PdfFontResource> chartFonts, PptxRenderContext context, List<PdfLinkAnnotation> linkAnnotations, HashSet<string> reportedHyperlinkIds, Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        string? title = sceneChart.Title.Text;
        if (string.IsNullOrWhiteSpace(title))
        {
            return;
        }

        ChartFrameBox frame = GetChartFrameBox(document, bounds);
        double x = frame.X;
        double y = frame.Y;
        double width = frame.Width;
        double height = frame.Height;
        bool titleManualLayoutApplied = false;
        if (sceneChart.Title.Layout.HasLayout &&
            TryBuildManualLayoutBox(sceneChart.Title.Layout, frame, new ChartLayoutBox(frame.X, frame.Y, frame.Width, frame.Height), out ChartLayoutBox titleBox, true, false))
        {
            x = titleBox.X;
            y = titleBox.Y;
            width = titleBox.Width;
            height = titleBox.Height;
            titleManualLayoutApplied = true;
        }

        bool isAutoTitle = sceneChart.Title.IsAutoGenerated;
        ChartTextStyle style = ReadChartTitleTextStyle(theme, sceneChart);
        double fontSize = style.FontSize;
        double titleBaselineRatio = !titleManualLayoutApplied && HasPolarChart(sceneChart)
            ? PptxChartMetricRules.PolarTitleBaselineYRatio
            : PptxChartMetricRules.TitleBaselineYRatio;
        // Polar auto titles sit a fixed inset below the title-box top (Office keeps 476.0 across
        // frame heights); every other title keeps the ratio fallback.
        bool usePolarTitleTopOffset = !titleManualLayoutApplied && isAutoTitle && HasPolarChart(sceneChart);
        double fallbackBaselineY = usePolarTitleTopOffset
            ? y + height - PptxChartMetricRules.PolarTitleTopOffset
            : y + height * titleBaselineRatio;
        double baselineY = titleManualLayoutApplied
            ? fallbackBaselineY
            : (await ResolveChartTitleBaselineYAsync(document, theme, colorMap, bounds, chartXml, sceneChart, workbook, plotVisibleOnly, fallbackBaselineY, fontSize, fontResolver).ConfigureAwait(false));
        double titleX = x + width * PptxChartMetricRules.TitleXInsetRatio;
        double titleWidth = width * PptxChartMetricRules.TitleWidthRatio;
        double titleHeight = fontSize * PptxChartMetricRules.TitleHeightFactor;
        var runs = new List<TextRun>();
        List<ChartTextRunLink>? titleLinks = sceneChart.Relationships is null ? null : new List<ChartTextRunLink>();
        await AddChartRichTextRunsAsync(
            runs,
            ReadChartTitleTextRuns(sceneChart),
            title.Trim(),
            titleX,
            baselineY,
            titleWidth,
            titleHeight,
            x,
            y,
            width,
            height,
            style,
            TextAlignment.Center,
            fontResolver,
            titleLinks).ConfigureAwait(false);
        ChartShapeStyle titleShape = ToChartShapeStyle(sceneChart.Title.ShapeStyle);
        if (!titleShape.IsEmpty)
        {
            ChartLayoutBox paintBox = titleManualLayoutApplied
                ? new ChartLayoutBox(x, y, width, height)
                : await MeasureChartTitlePaintBoxAsync(runs, style, fontResolver).ConfigureAwait(false);
            RenderChartShapeStyle(graphics, paintBox.X, paintBox.Y, paintBox.Width, paintBox.Height, titleShape);
        }
        RenderedFonts titleFonts = (await RenderChartTextRunsAsync(runs, graphics, chartFonts, "CT", fontResolver, diagnosticSink).ConfigureAwait(false));
        if (titleLinks is not null && sceneChart.Relationships is not null)
        {
            foreach (ChartTextRunLink titleLink in titleLinks)
            {
                AddChartTextRunHyperlinkAnnotation(titleLink, sceneChart.Relationships, context, sceneChart.TargetPartName, linkAnnotations, reportedHyperlinkIds, titleFonts.Fonts);
            }
        }
    }

    private static async ValueTask<ChartLayoutBox> MeasureChartTitlePaintBoxAsync(
        IReadOnlyList<TextRun> runs, ChartTextStyle style, PresentationFontResolver resolver)
    {
        var measure = new ChartTextMeasurer(resolver);
        double left = double.PositiveInfinity, bottom = double.PositiveInfinity;
        double right = double.NegativeInfinity, top = double.NegativeInfinity;
        foreach (TextRun run in runs)
        {
            ChartTextStyle runStyle = style with
            {
                FontFamily = run.FontFamily, FontSize = run.FontSize,
                Bold = run.Bold, Italic = run.Italic, CharacterSpacing = run.CharacterSpacing
            };
            double advance = await measure.MeasureAsync(run.Text, runStyle).ConfigureAwait(false);
            var line = await measure.MeasureLineBoxAsync(runStyle, horizontalHeader: true).ConfigureAwait(false);
            double x = run.X + (run.Alignment switch
            {
                TextAlignment.Center => Math.Max(0d, run.Width - advance) / 2d,
                TextAlignment.Right => Math.Max(0d, run.Width - advance),
                _ => 0d
            });
            double baseline = run.Y + run.BaselineOffset;
            left = Math.Min(left, Math.Min(x, x + advance));
            right = Math.Max(right, Math.Max(x, x + advance));
            top = Math.Max(top, baseline + line.Ascent);
            bottom = Math.Min(bottom, baseline + line.Ascent - line.Height);
        }
        double horizontal = PptxChartMetricRules.ChartTitleHorizontalPadding;
        double vertical = PptxChartMetricRules.ChartTitleLinePadding;
        // Paint the measured caption box. Text and links retain their existing
        // frame clip, including glyph overhang; each chart family owns placement.
        return new ChartLayoutBox(left - horizontal, bottom - vertical,
            Math.Max(1d, right - left + 2d * horizontal), Math.Max(1d, top - bottom + 2d * vertical));
    }

    private static async ValueTask RenderManualChartAxisTitlesAsync(
        PptxDocument document,
        PptxTheme theme,
        PdfGraphicsBuilder graphics,
        ShapeBounds bounds,
        PptxSceneChart sceneChart,
        PresentationFontResolver fontResolver,
        Action<OoxPdfDiagnostic>? diagnosticSink,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds)
    {
        ChartFrameBox frame = GetChartFrameBox(document, bounds);
        foreach (PptxSceneChartAxis axis in sceneChart.Axes)
        {
            if (!string.IsNullOrWhiteSpace(axis.Title.Text) && !axis.Title.Layout.HasLayout)
            {
                continue;
            }

            await RenderManualChartAxisTitleAsync(
                theme,
                graphics,
                frame,
                axis.Title.Text,
                ToChartTextRuns(axis.Title.TextRuns),
                axis.Title.Layout,
                ToChartShapeStyle(axis.Title.ShapeStyle),
                ToChartTextStyleOverride(PptxSceneBuilder.ResolveChartElementTextStyleOverride(sceneChart, axis.Title.TextStyle, GetChartAxisStyleRole(axis.AxisKind))),
                ChartTextStyleOverride.Empty,
                ChartTextStyleOverride.Empty,
                fontResolver, chartFonts, context, sceneChart.Relationships, linkAnnotations, reportedHyperlinkIds, diagnosticSink).ConfigureAwait(false);
        }
    }

    private static async ValueTask RenderDefaultChartAxisTitlesAsync(
        PptxTheme theme,
        PdfGraphicsBuilder graphics,
        ChartLayout layout,
        PptxSceneChart sceneChart,
        PresentationFontResolver fontResolver,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds,
        Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        foreach (PptxSceneChartAxis axis in sceneChart.Axes)
        {
            if (axis.IsDeleted == true ||
                string.IsNullOrWhiteSpace(axis.Title.Text) ||
                axis.Title.Layout.HasLayout)
            {
                continue;
            }

            await RenderDefaultChartAxisTitleAsync(
                theme,
                graphics,
                layout,
                axis.Title.Text,
                ToChartTextRuns(axis.Title.TextRuns),
                axis.AxisKind,
                axis.PositionKind,
                ToChartShapeStyle(axis.Title.ShapeStyle),
                ToChartTextStyleOverride(PptxSceneBuilder.ResolveChartElementTextStyleOverride(sceneChart, axis.Title.TextStyle, GetChartAxisStyleRole(axis.AxisKind))),
                ChartTextStyleOverride.Empty,
                ToChartTextStyleOverride(axis.Title.TextStyle),
                fontResolver, chartFonts, context, sceneChart.Relationships, linkAnnotations, reportedHyperlinkIds, diagnosticSink).ConfigureAwait(false);
        }
    }

    private static void EmitUnrenderedDefaultChartAxisTitleDiagnostics(
        PptxSceneChart sceneChart,
        Action<OoxPdfDiagnostic>? diagnosticSink,
        string? chartPartName,
        int slideIndex)
    {
        if (diagnosticSink is null)
        {
            return;
        }

        foreach (PptxSceneChartAxis axis in sceneChart.Axes)
        {
            if (axis.IsDeleted == true ||
                string.IsNullOrWhiteSpace(axis.Title.Text) ||
                axis.Title.Layout.HasLayout ||
                IsRenderableDefaultChartAxisTitle(axis.AxisKind, axis.PositionKind))
            {
                continue;
            }

            EmitChartDiagnostic(diagnosticSink, "PPTX_UNSUPPORTED_CHART_AXIS_TITLE_AXIS_POSITION", OoxPdfSeverity.Warning, "Default-placement chart axis title has an unsupported or missing axis kind/position.", chartPartName, slideIndex, "Ignored");
        }
    }

    private static async ValueTask RenderDefaultChartAxisTitleAsync(
        PptxTheme theme,
        PdfGraphicsBuilder graphics,
        ChartLayout layout,
        string? text,
        IReadOnlyList<ChartTextRunOverride> textRuns,
        PptxSceneChartAxisKind axisKind,
        PptxSceneChartAxisPosition positionKind,
        ChartShapeStyle shapeStyle,
        ChartTextStyleOverride chartTextStyle,
        ChartTextStyleOverride chartStyleRoleTextStyle,
        ChartTextStyleOverride titleTextStyle,
        PresentationFontResolver fontResolver,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        IReadOnlyDictionary<string, OoxRelationship>? chartRelationships,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds,
        Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return;
        }

        ChartTextStyle style = CreateDefaultChartTextStyle(theme, fallbackFontSize: PptxChartMetricRules.TitleFallbackFontSize);
        style = style.Merge(chartTextStyle);
        style = style.Merge(chartStyleRoleTextStyle);
        style = style.Merge(titleTextStyle);
        if (titleTextStyle.Bold is null)
        {
            style = style with { Bold = true };
        }

        if (titleTextStyle.Color is null)
        {
            style = style with { Color = new RgbColor(0, 0, 0) };
        }
        string trimmed = text.Trim();
        double titleHeight = style.FontSize * PptxChartMetricRules.TitleHeightFactor;
        var textMeasurer = new ChartTextMeasurer(fontResolver);
        double textWidth = Math.Max(style.FontSize, (await textMeasurer.MeasureAsync(trimmed, style).ConfigureAwait(false)));
        if (!IsRenderableDefaultChartAxisTitle(axisKind, positionKind))
        {
            return;
        }

        if (positionKind is PptxSceneChartAxisPosition.Bottom or PptxSceneChartAxisPosition.Top)
        {
            await RenderDefaultHorizontalChartAxisTitleAsync(graphics, layout, trimmed, textRuns, style, shapeStyle, titleHeight, textWidth, positionKind, fontResolver, chartFonts, context, chartRelationships, linkAnnotations, reportedHyperlinkIds, diagnosticSink).ConfigureAwait(false);
        }
        else if (positionKind is PptxSceneChartAxisPosition.Left or PptxSceneChartAxisPosition.Right)
        {
            await RenderDefaultVerticalChartAxisTitleAsync(graphics, layout, trimmed, textRuns, style, shapeStyle, titleHeight, textWidth, positionKind, fontResolver, chartFonts, context, chartRelationships, linkAnnotations, reportedHyperlinkIds, diagnosticSink).ConfigureAwait(false);
        }
    }

    // Bottom default axis-title baseline: frame bottom plus 0.338 times the
    // plot-to-frame reserve (two Office renders agree within 0.01pt).
    private static double ComputeDefaultBottomAxisTitleBaselineY(double frameBottomY, double plotBottomY)
    {
        double bottomReserve = Math.Max(0d, plotBottomY - frameBottomY);
        return frameBottomY + bottomReserve * PptxChartMetricRules.DefaultAxisTitleBandBaselineRatio;
    }

    private static bool IsRenderableDefaultChartAxisTitle(PptxSceneChartAxisKind axisKind, PptxSceneChartAxisPosition positionKind)
    {
        return positionKind switch
        {
            PptxSceneChartAxisPosition.Bottom or PptxSceneChartAxisPosition.Top =>
                axisKind is PptxSceneChartAxisKind.Category or PptxSceneChartAxisKind.Date or PptxSceneChartAxisKind.Series or PptxSceneChartAxisKind.Value,
            PptxSceneChartAxisPosition.Left or PptxSceneChartAxisPosition.Right =>
                axisKind is PptxSceneChartAxisKind.Value or PptxSceneChartAxisKind.Category or PptxSceneChartAxisKind.Date,
            _ => false
        };
    }

    private static string GetChartAxisStyleRole(PptxSceneChartAxisKind axisKind)
    {
        return axisKind switch
        {
            PptxSceneChartAxisKind.Value => "valueAxis",
            PptxSceneChartAxisKind.Category or PptxSceneChartAxisKind.Date or PptxSceneChartAxisKind.Series => "categoryAxis",
            _ => string.Empty
        };
    }

    private static async ValueTask RenderDefaultHorizontalChartAxisTitleAsync(
        PdfGraphicsBuilder graphics,
        ChartLayout layout,
        string text,
        IReadOnlyList<ChartTextRunOverride> textRuns,
        ChartTextStyle style,
        ChartShapeStyle shapeStyle,
        double titleHeight,
        double textWidth,
        PptxSceneChartAxisPosition positionKind,
        PresentationFontResolver? fontResolver,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        IReadOnlyDictionary<string, OoxRelationship>? chartRelationships,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds,
        Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        ChartFrameBox frame = layout.Frame;
        ChartPlotBox plotBox = layout.PlotBox;
        double titleX = plotBox.X + plotBox.Width / 2d - textWidth / 2d;
        double baselineY;
        double boxY;
        if (positionKind == PptxSceneChartAxisPosition.Top)
        {
            double topReserve = Math.Max(0d, frame.Y + frame.Height - plotBox.Y - plotBox.Height);
            baselineY = plotBox.Y + plotBox.Height + topReserve * PptxChartMetricRules.DefaultAxisTitleTopBandBaselineRatio;
            boxY = Math.Max(plotBox.Y + plotBox.Height, baselineY - titleHeight);
        }
        else
        {
            baselineY = ComputeDefaultBottomAxisTitleBaselineY(frame.Y, plotBox.Y);
            boxY = Math.Max(frame.Y, baselineY - titleHeight);
        }

        double boxX = Math.Max(frame.X, titleX - style.FontSize * 0.5d);
        double boxWidth = Math.Min(frame.X + frame.Width - boxX, textWidth + style.FontSize);
        RenderChartShapeStyle(graphics, boxX, boxY, boxWidth, titleHeight, shapeStyle);
        var runs = new List<TextRun>();
        List<ChartTextRunLink>? axisLinks = chartRelationships is null ? null : new List<ChartTextRunLink>();
        await AddChartRichTextRunsAsync(
            runs,
            textRuns,
            text,
            titleX,
            baselineY,
            textWidth,
            titleHeight,
            frame.X,
            frame.Y,
            frame.Width,
            frame.Height,
            style,
            TextAlignment.Center,
            fontResolver,
            axisLinks).ConfigureAwait(false);
        RenderedFonts axisFonts = (await RenderChartTextRunsAsync(runs, graphics, chartFonts, "CAT", fontResolver, diagnosticSink).ConfigureAwait(false));
        AddChartTextRunHyperlinkAnnotations(axisLinks, chartRelationships, context, axisFonts, linkAnnotations, reportedHyperlinkIds);
    }

    private static async ValueTask RenderDefaultVerticalChartAxisTitleAsync(
        PdfGraphicsBuilder graphics,
        ChartLayout layout,
        string text,
        IReadOnlyList<ChartTextRunOverride> textRuns,
        ChartTextStyle style,
        ChartShapeStyle shapeStyle,
        double titleHeight,
        double textWidth,
        PptxSceneChartAxisPosition positionKind,
        PresentationFontResolver? fontResolver,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        IReadOnlyDictionary<string, OoxRelationship>? chartRelationships,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds,
        Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        ChartFrameBox frame = layout.Frame;
        ChartPlotBox plotBox = layout.PlotBox;
        bool rightSide = positionKind == PptxSceneChartAxisPosition.Right;
        double sideReserve = rightSide
            ? Math.Max(0d, frame.X + frame.Width - plotBox.X - plotBox.Width)
            : Math.Max(0d, plotBox.X - frame.X);
        double sideBaselineRatio = rightSide
            ? PptxChartMetricRules.DefaultAxisTitleRightSideBaselineRatio
            : PptxChartMetricRules.DefaultAxisTitleLeftSideBaselineRatio;
        double baselineX = rightSide
            ? plotBox.X + plotBox.Width + sideReserve * sideBaselineRatio
            : frame.X + PptxChartMetricRules.DefaultAxisTitleLeftColumnOffset;
        // Office centers the title ink on the plot middle: the TJ origin sits exactly
        // at mid minus half the EMITTED width on three cached references (bar 253.9 vs
        // 253.7, column 280.95 vs 280.8, top-right 245.09 vs 245.0). The caller-measured
        // textWidth uses the chart-level size while runs emit at run-level sizes, so the
        // width is remeasured here with the merged run styles that drive emission.
        double emittedTitleWidth = 0d;
        if (textRuns.Count != 0)
        {
            var titleMeasurer = new ChartTextMeasurer(fontResolver);
            foreach (ChartTextRunOverride titleRun in textRuns)
            {
                if (!string.IsNullOrEmpty(titleRun.Text))
                {
                    emittedTitleWidth += Math.Max(0d, (await titleMeasurer.MeasureAsync(titleRun.Text, style.Merge(titleRun.TextStyle)).ConfigureAwait(false)));
                }
            }
        }

        double centeredTitleWidth = emittedTitleWidth > 0d ? emittedTitleWidth : textWidth;
        double baselineY = plotBox.Y + plotBox.Height / 2d - centeredTitleWidth / 2d;
        double boxX = Math.Max(frame.X, Math.Min(frame.X + frame.Width - titleHeight, baselineX - titleHeight * 0.5d));
        double boxY = Math.Max(frame.Y, Math.Min(frame.Y + frame.Height - textWidth, baselineY));
        RenderChartShapeStyle(graphics, boxX, boxY, titleHeight, textWidth, shapeStyle);
        var runs = new List<TextRun>();
        List<ChartTextRunLink>? axisLinks = chartRelationships is null ? null : new List<ChartTextRunLink>();
        await AddChartRichTextRunsAsync(
            runs,
            textRuns,
            text,
            baselineX,
            baselineY,
            textWidth,
            titleHeight,
            frame.X,
            frame.Y,
            frame.Width,
            frame.Height,
            style,
            TextAlignment.Left,
            fontResolver,
            axisLinks).ConfigureAwait(false);
        double rotation = -90d;
        for (int i = 0; i < runs.Count; i++)
        {
            TextRun run = runs[i];
            runs[i] = run with
            {
                RotationDegrees = rotation,
                RotationCenterX = run.X,
                RotationCenterY = run.Y
            };
        }

        if (axisLinks is not null)
        {
            for (int linkIndex = 0; linkIndex < axisLinks.Count; linkIndex++)
            {
                ChartTextRunLink axisLink = axisLinks[linkIndex];
                TextRun linkedRun = axisLink.Run;
                axisLinks[linkIndex] = axisLink with
                {
                    Run = linkedRun with
                    {
                        RotationDegrees = rotation,
                        RotationCenterX = linkedRun.X,
                        RotationCenterY = linkedRun.Y
                    }
                };
            }
        }

        RenderedFonts axisFonts = (await RenderChartTextRunsAsync(runs, graphics, chartFonts, "CAT", fontResolver, diagnosticSink).ConfigureAwait(false));
        AddChartTextRunHyperlinkAnnotations(axisLinks, chartRelationships, context, axisFonts, linkAnnotations, reportedHyperlinkIds);
    }

    private static async ValueTask RenderManualChartAxisTitleAsync(
        PptxTheme theme,
        PdfGraphicsBuilder graphics,
        ChartFrameBox frame,
        string? text,
        IReadOnlyList<ChartTextRunOverride> textRuns,
        PptxSceneChartManualLayout layout,
        ChartShapeStyle shapeStyle,
        ChartTextStyleOverride chartTextStyle,
        ChartTextStyleOverride chartStyleRoleTextStyle,
        ChartTextStyleOverride titleTextStyle,
        PresentationFontResolver? fontResolver,
        List<PdfFontResource> chartFonts,
        PptxRenderContext context,
        IReadOnlyDictionary<string, OoxRelationship>? chartRelationships,
        List<PdfLinkAnnotation> linkAnnotations,
        HashSet<string> reportedHyperlinkIds,
        Action<OoxPdfDiagnostic>? diagnosticSink = null)
    {
        if (string.IsNullOrWhiteSpace(text) ||
            !TryBuildManualLayoutBox(layout, frame, new ChartLayoutBox(frame.X, frame.Y, frame.Width, frame.Height), out ChartLayoutBox titleBox, true, false))
        {
            return;
        }

        ChartTextStyle style = CreateDefaultChartTextStyle(theme, fallbackFontSize: PptxChartMetricRules.TitleFallbackFontSize);
        style = style.Merge(chartTextStyle);
        style = style.Merge(chartStyleRoleTextStyle);
        style = style.Merge(titleTextStyle);
        RenderChartShapeStyle(graphics, titleBox.X, titleBox.Y, titleBox.Width, titleBox.Height, shapeStyle);
        double titleHeight = style.FontSize * PptxChartMetricRules.TitleHeightFactor;
        double baselineY = titleBox.Y + titleBox.Height * PptxChartMetricRules.TitleBaselineYRatio;
        var runs = new List<TextRun>();
        List<ChartTextRunLink>? axisLinks = chartRelationships is null ? null : new List<ChartTextRunLink>();
        await AddChartRichTextRunsAsync(
            runs,
            textRuns,
            text.Trim(),
            titleBox.X + titleBox.Width * PptxChartMetricRules.TitleXInsetRatio,
            baselineY,
            titleBox.Width * PptxChartMetricRules.TitleWidthRatio,
            titleHeight,
            titleBox.X,
            titleBox.Y,
            titleBox.Width,
            titleBox.Height,
            style,
            TextAlignment.Center,
            fontResolver,
            axisLinks).ConfigureAwait(false);
        RenderedFonts axisFonts = (await RenderChartTextRunsAsync(runs, graphics, chartFonts, "CAT", fontResolver, diagnosticSink).ConfigureAwait(false));
        AddChartTextRunHyperlinkAnnotations(axisLinks, chartRelationships, context, axisFonts, linkAnnotations, reportedHyperlinkIds);
    }

    private static ChartAxisTitleReserveSides ReadDefaultAxisTitleReserveSides(PptxSceneChart sceneChart)
    {
        var reserveSides = new ChartAxisTitleReserveSides();
        foreach (PptxSceneChartAxis axis in sceneChart.Axes)
        {
            if (axis.IsDeleted == true ||
                string.IsNullOrWhiteSpace(axis.Title.Text) ||
                axis.Title.Layout.HasLayout ||
                !IsRenderableDefaultChartAxisTitle(axis.AxisKind, axis.PositionKind))
            {
                continue;
            }

            reserveSides = reserveSides.With(axis.PositionKind);
        }

        return reserveSides;
    }

    private static bool HasPolarChart(PptxSceneChart sceneChart)
    {
        return sceneChart.Plots.Any(plot =>
            plot.PlotKind is PptxSceneChartPlotKind.Pie or
                PptxSceneChartPlotKind.Doughnut or
                PptxSceneChartPlotKind.Radar);
    }

    private static async ValueTask<double> ResolveChartTitleBaselineYAsync(PptxDocument document, PptxTheme theme, PptxColorMap colorMap, ShapeBounds bounds, XDocument chartXml, PptxSceneChart sceneChart, ChartWorkbookData? workbook, bool plotVisibleOnly, double fallbackBaselineY, double fontSize, PresentationFontResolver? fontResolver)
    {
        XElement? barChart = ReadSceneOrXmlFirstChartPlotElement(sceneChart, chartXml, PptxSceneChartPlotKind.Bar);
        if (barChart is null)
        {
            // Line charts anchor auto titles above the plot like bars do: Office puts the
            // trend and composite single-series titles exactly one auto factor (1.08) above
            // the plot top. Scatter charts share the line layout path; bubble charts use
            // their own layout but follow the same law (Markets title at plot top plus
            // 1.08fs). Explicit titles keep the frame-ratio fallback (uncalibrated).
            XElement? bubbleChart = ReadSceneOrXmlFirstChartPlotElement(sceneChart, chartXml, PptxSceneChartPlotKind.Bubble);
            if (bubbleChart is not null && sceneChart.Title.IsAutoGenerated)
            {
                PptxSceneChartPlot? bubblePlot = ReadSceneChartPlot(sceneChart, PptxSceneChartPlotKind.Bubble, 0);
                ChartLayout bubbleLayout = GetBubbleChartLayout(document, theme, bounds, chartXml, sceneChart, colorMap);
                return bubbleLayout.PlotBox.Y + bubbleLayout.PlotBox.Height + fontSize * PptxChartMetricRules.AutoBarTitleAbovePlotBaselineOffsetFactor;
            }

            XElement? pointChart = ReadSceneOrXmlFirstChartPlotElement(sceneChart, chartXml, PptxSceneChartPlotKind.Line)
                ?? ReadSceneOrXmlFirstChartPlotElement(sceneChart, chartXml, PptxSceneChartPlotKind.Scatter);
            if (pointChart is null || !sceneChart.Title.IsAutoGenerated)
            {
                return fallbackBaselineY;
            }

            ChartLayout lineLayout = (await GetLineChartLayoutAsync(document, theme, bounds, chartXml, sceneChart, colorMap, workbook, plotVisibleOnly, fontResolver).ConfigureAwait(false));
            return lineLayout.PlotBox.Y + lineLayout.PlotBox.Height + fontSize * PptxChartMetricRules.AutoBarTitleAbovePlotBaselineOffsetFactor;
        }

        PptxSceneChartPlot? barPlot = ReadSceneChartPlot(sceneChart, PptxSceneChartPlotKind.Bar, 0);
        ChartBarPlotOptions barOptions = ReadSceneOrXmlChartBarOptions(barPlot, barChart, PptxSceneChartGrouping.Clustered);
        bool horizontalBars = barOptions.BarDirection == PptxSceneChartBarDirection.Bar;
        ChartLayout layout = (await GetBarChartLayoutAsync(document, theme, bounds, chartXml, sceneChart, colorMap, barPlot, barChart, barOptions, workbook, plotVisibleOnly, fontResolver).ConfigureAwait(false));
        if (layout.AutomaticTitleBaselineY is { } measuredBaseline) { return measuredBaseline; }
        ChartPlotBox titleAnchorBox = layout.PlotBox;
        if (horizontalBars && layout.ManualPlotLayoutApplied && sceneChart.Title.IsAutoGenerated)
        {
            ChartFrameBox frame = GetChartFrameBox(document, bounds);
            ChartLegendLayout legend = ReadSceneOrXmlChartLegendLayout(theme, colorMap, sceneChart, chartXml);
            titleAnchorBox = (await GetBarChartPlotLayoutAsync(
                theme,
                colorMap,
                frame,
                chartXml,
                sceneChart,
                barPlot,
                barChart,
                sceneChart.Title.Text,
                legend,
                barOptions,
                workbook,
                plotVisibleOnly,
                ignoreManualPlotLayout: true,
                fontResolver: fontResolver).ConfigureAwait(false)).PlotBox;
        }

        double offsetFactor = !horizontalBars && sceneChart.Title.IsAutoGenerated
            ? PptxChartMetricRules.AutoBarTitleAbovePlotBaselineOffsetFactor
            : PptxChartMetricRules.TitleAbovePlotBaselineOffsetFactor;
        return titleAnchorBox.Y + titleAnchorBox.Height + fontSize * offsetFactor;
    }

    private static async ValueTask<(double Ascent, double Height)> MeasureChartTitleLineAsync(
        PptxTheme theme, PptxSceneChart sceneChart, PresentationFontResolver? resolver)
    {
        ChartTextStyle style = ReadChartTitleTextStyle(theme, sceneChart);
        var measure = new ChartTextMeasurer(resolver);
        double ascent = 0d, height = 0d;
        bool hasRuns = false;
        foreach (ChartTextRunOverride run in ReadChartTitleTextRuns(sceneChart))
        {
            if (string.IsNullOrEmpty(run.Text)) { continue; }
            var line = await measure.MeasureLineBoxAsync(style.Merge(run.TextStyle), horizontalHeader: true).ConfigureAwait(false);
            ascent = Math.Max(ascent, line.Ascent);
            height = Math.Max(height, line.Height);
            hasRuns = true;
        }
        if (!hasRuns)
        {
            var line = await measure.MeasureLineBoxAsync(style, horizontalHeader: true).ConfigureAwait(false);
            return (line.Ascent, line.Height);
        }
        return (ascent, height);
    }

    private static ChartTextStyle ReadChartTitleTextStyle(PptxTheme theme, PptxSceneChart sceneChart)
    {
        ChartTextStyle style = CreateDefaultChartTextStyle(theme, sceneChart.ColorMap, fallbackFontSize: PptxChartMetricRules.TitleFallbackFontSize);
        style = style.Merge(ToChartTextStyleOverride(PptxSceneBuilder.ResolveChartTitleTextStyleOverride(sceneChart)));
        if (!sceneChart.Title.IsAutoGenerated)
        {
            return style;
        }

        return style with
        {
            Bold = true
        };
    }

    private static IReadOnlyList<ChartTextRunOverride> ReadChartTitleTextRuns(PptxSceneChart sceneChart)
    {
        return sceneChart.Title.IsAutoGenerated ? [] : ToChartTextRuns(sceneChart.Title.TextRuns);
    }

    private static ChartIndexedTextVector ReadChartCategoryLabelVector(XElement chartElement, ChartWorkbookData? workbook, bool plotVisibleOnly)
    {
        XElement? categories = chartElement
            .Element(ChartNamespace + "ser")
            ?.Element(ChartNamespace + "cat");
        if (categories is null)
        {
            return default;
        }

        XElement? cache = categories
            .Descendants(ChartNamespace + "strCache")
            .Concat(categories.Descendants(ChartNamespace + "strLit"))
            .Concat(categories.Descendants(ChartNamespace + "numCache"))
            .Concat(categories.Descendants(ChartNamespace + "numLit"))
            .Concat(categories.Descendants(ChartNamespace + "multiLvlStrCache"))
            .FirstOrDefault();
        PptxSceneChartDataSource source = PptxSceneBuilder.ReadChartDataSource(categories, "strRef", "numRef", "multiLvlStrRef");
        if (cache is null)
        {
            return new ChartIndexedTextVector(
                [],
                null,
                [],
                source.Formula,
                source,
                ReadWorkbookTextPoints(workbook, source),
                plotVisibleOnly);
        }

        IEnumerable<XElement> pointElements = cache.Name.LocalName == "multiLvlStrCache"
            ? cache.Descendants(ChartNamespace + "pt")
            : cache.Elements(ChartNamespace + "pt");
        ChartIndexedTextPoint[] points = ReadChartIndexedTextPoints(pointElements);
        IReadOnlyList<IReadOnlyList<ChartIndexedTextPoint>> levels = cache.Name.LocalName == "multiLvlStrCache"
            ? cache
                .Elements(ChartNamespace + "lvl")
                .Select(level => ReadChartIndexedTextPoints(level.Elements(ChartNamespace + "pt")))
                .Where(level => level.Length != 0)
                .ToArray()
            : [];
        return new ChartIndexedTextVector(
            points,
            PptxSceneBuilder.ReadChartCachePointCount(cache).Value ?? InferPointCount(points),
            levels,
            source.Formula,
            source,
            ReadWorkbookTextPoints(workbook, source),
            plotVisibleOnly);
    }

    private static ChartIndexedTextPoint[] ReadChartIndexedTextPoints(IEnumerable<XElement> sourcePoints)
    {
        return PptxSceneBuilder
            .ReadChartStringPoints(sourcePoints, requireNonNegativeIndex: true)
            .Select(point => ToChartIndexedTextPoint(point, trimText: true))
            .ToArray();
    }
