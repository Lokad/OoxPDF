    private static bool TryResolveFractionCurveVaryColorsFill(int categoryIndex, int valuePointCount, out RgbColor fill)
    {
        fill = default;
        if (valuePointCount < FractionCurveVaryColorsPointThreshold)
        {
            return false;
        }

        int accent = categoryIndex % 6;
        int level = categoryIndex / 6;
        if (level == 0)
        {
            byte[] eraBases = FractionCurveVaryColorsEra(valuePointCount) switch
            {
                0 => FractionCurveEra0Bases,
                1 => FractionCurveEra1Bases,
                _ => FractionCurveEra2Bases,
            };
            fill = new RgbColor(eraBases[accent * 3], eraBases[accent * 3 + 1], eraBases[accent * 3 + 2]);
            return true;
        }

        int cap = valuePointCount / 6;
        double position = ((double)level / cap) * 100d;
        if (position < 0d) position = 0d;
        if (position > 100d) position = 100d;
        int lo = (int)position;
        if (lo >= 100)
        {
            fill = CurveColor(accent, 100);
            return true;
        }

        double w = position - lo;
        RgbColor c0 = CurveColor(accent, lo);
        RgbColor c1 = CurveColor(accent, lo + 1);
        fill = new RgbColor(
            RoundByte(c0.Red + (c1.Red - c0.Red) * w),
            RoundByte(c0.Green + (c1.Green - c0.Green) * w),
            RoundByte(c0.Blue + (c1.Blue - c0.Blue) * w));
        return true;
    }

    private static RgbColor CurveColor(int accent, int entry)
    {
        byte[] curve = accent switch
        {
            0 => FractionCurveAccent1,
            1 => FractionCurveAccent2,
            2 => FractionCurveAccent3,
            3 => FractionCurveAccent4,
            4 => FractionCurveAccent5,
            _ => FractionCurveAccent6,
        };
        return new RgbColor(curve[entry * 3], curve[entry * 3 + 1], curve[entry * 3 + 2]);
    }

    private static byte RoundByte(double value)
    {
        return (byte)System.Math.Clamp((int)System.Math.Round(value, System.MidpointRounding.AwayFromZero), 0, 255);
    }
