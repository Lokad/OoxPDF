"""Regenerate bounded owning/continuation-cell mathematics controls."""
import copy,hashlib,json
from pathlib import Path
from zipfile import ZipFile,ZIP_DEFLATED
from xml.etree import ElementTree as E
root=Path(__file__).resolve().parent.parent
output=root/'tests/Lokad.OoxPdf.Tests/Cases/CompositionProbes'
source=output.parent/'docx-omml-table-inline-fraction.docx'
w='{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
with ZipFile(source) as archive:
 infos=archive.infolist()
 parts={i.filename:archive.read(i.filename) for i in infos}
for case in json.loads((output/'merged-math-cells.json').read_text()):
 assert hashlib.sha256(source.read_bytes()).hexdigest().upper()==case['SourceSha256']
 tree=E.fromstring(parts['word/document.xml']);table=next(tree.iter(w+'tbl'))
 first=table.find(w+'tr');second=copy.deepcopy(first)
 for cell in second.findall(w+'tc'):
  for item in list(cell):
   if item.tag!=w+'tcPr':cell.remove(item)
  E.SubElement(cell,w+'p')
 table.append(second)
 if case['Id']=='merged-math-cell':
  for row,value in zip(table.findall(w+'tr'),['restart','continue']):
   cell=row.find(w+'tc');properties=cell.find(w+'tcPr')
   if properties is None:properties=E.Element(w+'tcPr');cell.insert(0,properties)
   E.SubElement(properties,w+'vMerge',{w+'val':value})
 data=E.tostring(tree,encoding='utf-8',xml_declaration=True)
 from io import BytesIO
 buffer=BytesIO()
 with ZipFile(buffer,'w',ZIP_DEFLATED) as archive:
  for info in infos:archive.writestr(copy.copy(info),data if info.filename=='word/document.xml' else parts[info.filename])
 data=buffer.getvalue()
 assert hashlib.sha256(data).hexdigest().upper()==case['Sha256']
 (root/case['Input']).write_bytes(data)
print('Two merged-cell controls regenerated byte-identically.')
