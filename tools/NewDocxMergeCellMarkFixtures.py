"""Regenerate source-pinned cell-terminal mark/visible-run ownership controls."""
import copy
import hashlib
import json
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from xml.etree import ElementTree as E

root = Path(__file__).resolve().parent.parent
cases = root / 'tests/Lokad.OoxPdf.Tests/Cases/CompositionProbes/merge-cell-mark-floors.json'
w = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
sha = lambda data: hashlib.sha256(data).hexdigest().upper()
for case in json.loads(cases.read_text()):
    source = (root / case['Source']).read_bytes()
    assert sha(source) == case['SourceSha256'], case['Id']
    with ZipFile(BytesIO(source)) as archive:
        infos = archive.infolist()
        parts = {info.filename: archive.read(info.filename) for info in infos}
    tree = E.fromstring(parts['word/document.xml'])
    table = tree.find('.//' + w + 'tbl')
    variant = case['Variant']
    if variant in ['marker-face', 'source-face']:
        paragraph = table.find(w + 'tr').find(w + 'tc').find(w + 'p')
        properties = (paragraph.find(w + 'pPr').find(w + 'rPr') if variant == 'marker-face'
            else paragraph.find(w + 'r').find(w + 'rPr'))
        E.SubElement(properties, w + 'rFonts', {w + 'ascii': 'Cambria Math', w + 'hAnsi': 'Cambria Math'})
    else:
        table.find(w + 'tblPr').find(w + 'tblW').set(w + 'w', '6000')
        grid = table.find(w + 'tblGrid')
        grid.remove(list(grid)[-1])
        rows = table.findall(w + 'tr')
        for row in rows:
            row.remove(row.findall(w + 'tc')[-1])
        if variant == 'source-run':
            rows[0].find(w + 'tc').find(w + 'p').find(w + 'r').find(w + 'rPr').find(w + 'sz').set(w + 'val', '40')
        if variant == 'continuation-mark':
            E.SubElement(E.SubElement(E.SubElement(rows[1].find(w + 'tc').find(w + 'p'), w + 'pPr'), w + 'rPr'),
                w + 'sz', {w + 'val': '40'})
        if variant == 'default-size':
            styles = E.fromstring(parts['word/styles.xml'])
            styles.find(w + 'docDefaults').find(w + 'rPrDefault').find(w + 'rPr').find(w + 'sz').set(w + 'val', '28')
            parts['word/styles.xml'] = E.tostring(styles, encoding='utf-8', xml_declaration=True)
    parts['word/document.xml'] = E.tostring(tree, encoding='utf-8', xml_declaration=True)
    buffer = BytesIO()
    with ZipFile(buffer, 'w', ZIP_DEFLATED) as archive:
        for info in infos:
            archive.writestr(copy.copy(info), parts[info.filename])
    data = buffer.getvalue()
    assert sha(data) == case['Sha256'], case['Id']
    (root / case['Input']).write_bytes(data)
print('Ten cell-mark controls regenerated byte-identically.')
