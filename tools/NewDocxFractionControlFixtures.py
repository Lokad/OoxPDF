"""Regenerate source-pinned fraction metric controls without changing child runs."""
import copy
import hashlib
import json
from io import BytesIO
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED
from xml.etree import ElementTree as E

root = Path(__file__).resolve().parent.parent
output = root / 'tests/Lokad.OoxPdf.Tests/Cases/CompositionProbes'
w = '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
m = '{http://schemas.openxmlformats.org/officeDocument/2006/math}'
sha = lambda data: hashlib.sha256(data).hexdigest().upper()

for case in json.loads((output / 'fraction-control-frames.json').read_text()):
    source = (root / case['Source']).read_bytes()
    assert sha(source) == case['SourceSha256'], case['Id']
    with ZipFile(BytesIO(source)) as archive:
        infos = archive.infolist()
        parts = {info.filename: archive.read(info.filename) for info in infos}
    tree = E.fromstring(parts['word/document.xml'])
    body = tree.find(w + 'body')
    if case['Container'] == 'body' and case.get('FractionType') != 'noBar':
        table = body.find(w + 'tbl')
        paragraph = table.find(w + 'tr').find(w + 'tc').find(w + 'p')
        body.insert(list(body).index(table), copy.deepcopy(paragraph))
        body.remove(table)
    fraction = next(tree.iter(m + 'f'))
    properties = fraction.find(m + 'fPr')
    if properties is None:
        properties = E.Element(m + 'fPr')
        fraction.insert(0, properties)
    if case.get('FractionType') == 'noBar':
        properties.insert(0, E.Element(m + 'type', {m + 'val': 'noBar'}))
    else:
        control = E.SubElement(properties, m + 'ctrlPr')
        run = E.SubElement(control, w + 'rPr')
        if case['Container'].startswith('style'):
            E.SubElement(run, w + 'rStyle', {w + 'val': 'PublicFractionControl'})
            styles = E.fromstring(parts['word/styles.xml'])
            style = E.SubElement(styles, w + 'style',
                {w + 'type': 'character', w + 'styleId': 'PublicFractionControl'})
            E.SubElement(style, w + 'name', {w + 'val': 'Public fraction control'})
            run = E.SubElement(style, w + 'rPr')
            if case['Container'] == 'style-font':
                E.SubElement(run, w + 'rFonts', {w + 'ascii': 'Cambria Math', w + 'hAnsi': 'Cambria Math'})
            E.SubElement(run, w + 'sz', {w + 'val': str(case['ControlPoints'] * 2)})
            parts['word/styles.xml'] = E.tostring(styles, encoding='utf-8', xml_declaration=True)
        else:
            E.SubElement(run, w + 'sz', {w + 'val': str(case['ControlPoints'] * 2)})
    parts['word/document.xml'] = E.tostring(tree, encoding='utf-8', xml_declaration=True)
    buffer = BytesIO()
    with ZipFile(buffer, 'w', ZIP_DEFLATED) as archive:
        for info in infos:
            archive.writestr(copy.copy(info), parts[info.filename])
    data = buffer.getvalue()
    assert sha(data) == case['Sha256'], case['Id']
    (root / case['Input']).write_bytes(data)
print('Nine fraction-control inputs regenerated byte-identically.')
