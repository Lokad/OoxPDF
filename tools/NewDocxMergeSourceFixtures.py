"""Regenerate source-consumption controls from the qualified owning merge."""
import copy,hashlib,json
from pathlib import Path
from zipfile import ZipFile,ZIP_DEFLATED
from xml.etree import ElementTree as E
from io import BytesIO
root=Path(__file__).resolve().parent.parent
output=root/'tests/Lokad.OoxPdf.Tests/Cases/CompositionProbes'
source=output/'merged-math-cell.docx'
w='{http://schemas.openxmlformats.org/wordprocessingml/2006/main}'
with ZipFile(source) as archive:
 infos=archive.infolist();parts={i.filename:archive.read(i.filename) for i in infos}
cases=json.loads((output/'merged-source-consumption.json').read_text())
cases += [case for case in json.loads((output/'merged-span-admission.json').read_text())
          if case['Shape'] in ['minimum-rows','exact-rows']]
for case in cases:
 assert hashlib.sha256(source.read_bytes()).hexdigest().upper()==case['SourceSha256']
 tree=E.fromstring(parts['word/document.xml']);body=tree.find(w+'body');table=body.find(w+'tbl');rows=table.findall(w+'tr')
 shape=case['Shape']
 if shape=='three-rows':
  table.append(copy.deepcopy(rows[-1]))
 elif shape in ['minimum-rows','exact-rows']:
  for row in rows:
   properties=row.find(w+'trPr')
   if properties is None:properties=E.Element(w+'trPr');row.insert(0,properties)
   E.SubElement(properties,w+'trHeight',{w+'val':'100' if shape=='minimum-rows' else '300',
       w+'hRule':'atLeast' if shape=='minimum-rows' else 'exact'})
 elif shape=='page-boundary':
  table.find(w+'tblPr').find(w+'tblW').set(w+'w','8400')
  E.SubElement(table.find(w+'tblGrid'),w+'gridCol',{w+'w':'2400'})
  for number,row in enumerate(rows,1):
   cell=E.SubElement(row,w+'tc');pr=E.SubElement(cell,w+'tcPr')
   E.SubElement(pr,w+'tcW',{w+'w':'2400',w+'type':'dxa'})
   E.SubElement(E.SubElement(E.SubElement(cell,w+'p'),w+'r'),w+'t').text=f'Side row {number}.'
  spacer=E.Element(w+'p');pr=E.SubElement(spacer,w+'pPr')
  E.SubElement(pr,w+'spacing',{w+'before':'0',w+'after':'0',w+'line':'12600',w+'lineRule':'exact'})
  E.SubElement(E.SubElement(spacer,w+'r'),w+'t').text='Public page-boundary spacer.'
  body.insert(list(body).index(table),spacer)
 elif shape=='two-owners':
  table.append(copy.deepcopy(rows[-1]));rows=table.findall(w+'tr')
  grid=table.find(w+'tblGrid');grid[0].set(w+'w','4200')
  E.SubElement(grid,w+'gridCol',{w+'w':'4200'})
  table.find(w+'tblPr').find(w+'tblW').set(w+'w','8400')
  for index,row in enumerate(rows):
   original=row.find(w+'tc');original.find(w+'tcPr').find(w+'tcW').set(w+'w','4200')
   row.append(copy.deepcopy(original if index==0 else rows[1].find(w+'tc')))
   if index==2:
    first=row.find(w+'tc');first.find(w+'tcPr').remove(first.find(w+'tcPr').find(w+'vMerge'))
    E.SubElement(E.SubElement(first.find(w+'p'),w+'r'),w+'t').text='Tail after first owner.'
 else:raise ValueError('Unknown source-consumption shape')
 data=E.tostring(tree,encoding='utf-8',xml_declaration=True);buffer=BytesIO()
 with ZipFile(buffer,'w',ZIP_DEFLATED) as archive:
  for info in infos:archive.writestr(copy.copy(info),data if info.filename=='word/document.xml' else parts[info.filename])
 data=buffer.getvalue();assert hashlib.sha256(data).hexdigest().upper()==case['Sha256']
 (root/case['Input']).write_bytes(data)
print('Five merge source/row-floor controls regenerated byte-identically.')
