using System.Globalization;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Lokad.OoxPdf.Ooxml;
using Lokad.OoxPdf.Pptx;

namespace Lokad.OoxPdf.Tests;

internal static class PptxChartTitleDefaultsTests
{
    public static void PptxInferredTitleDefaultsMatchIndependentOfficeSizes()
    {
        string directory = Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "Cases", "ChartTitles"));
        using JsonDocument golden = JsonDocument.Parse(File.ReadAllText(Path.Combine(directory, "automatic-title-defaults-office.json")));
        double tolerance = golden.RootElement.GetProperty("FontSizeTolerancePoints").GetDouble();
        foreach (JsonElement control in golden.RootElement.GetProperty("Cases").EnumerateArray())
        {
            string input = Path.Combine(directory, control.GetProperty("Input").GetString()!);
            TestAssert.Equal(control.GetProperty("InputSha256").GetString(), Convert.ToHexString(SHA256.HashData(File.ReadAllBytes(input))));
            OoxPackage package = OoxPackage.Open(input, CancellationToken.None);
            PptxDocument document = new PptxReader().Read(package, CancellationToken.None);
            PptxSceneChart chart = new PptxSceneBuilder().Build(document, package, CancellationToken.None)
                .Slides[0].SlideNodes.Select(node => node.Chart).OfType<PptxSceneChart>().Single();
            TestAssert.True(chart.Title.IsAutoGenerated, "Each independent control must exercise an inferred title.");
            TestAssert.Equal(control.GetProperty("NominalSize").GetDouble(), PptxSceneBuilder.ResolveChartTitleTextStyleOverride(chart).FontSize!.Value);

            using var source = File.OpenRead(input);
            using var output = new MemoryStream();
            OoxPdfConverter.Convert(source, output, new OoxPdfOptions { InputKind = OoxPdfInputKind.Pptx, FontResolver = new TestFaceFontResolver() });
            Match show = Regex.Match(Encoding.ASCII.GetString(output.ToArray()), @"/CT[0-9]+ (?<size>[0-9.]+) Tf");
            TestAssert.True(show.Success, "The inferred title must paint with its own font resource.");
            double actual = double.Parse(show.Groups["size"].Value, CultureInfo.InvariantCulture);
            TestAssert.True(Math.Abs(actual - control.GetProperty("OfficeSize").GetDouble()) <= tolerance,
                "Inferred title size must match its independent Office control: " + Path.GetFileName(input));
        }
    }

    public static void PptxInferredTitleSizeFollowsSourcePrecedence()
    {
        const string modern = """
            <mc:AlternateContent><mc:Choice Requires="c14"><c14:style val="118"/></mc:Choice><mc:Fallback><c:style val="18"/></mc:Fallback></mc:AlternateContent>
            """;
        foreach (var row in new (string Selector, int? ChartSize, int? TitleSize, double Expected)[]
        {
            ("<c:style val=\"1\"/>", null, null, 18),
            ("<c:style val=\"48\"/>", null, null, 18),
            (modern, null, null, 18),
            ("<c14:style val=\"148\"/>", null, null, 18),
            ("", null, null, 10),
            ("<c:style val=\"2\"/>", 900, null, 10.8),
            ("", 1800, null, 21.6),
            ("<c:style val=\"2\"/>", 900, 1400, 14)
        })
        {
            string chartText = TextProperties(row.ChartSize);
            string title = row.TitleSize is null ? "" : "<c:title>" + TextProperties(row.TitleSize) + "</c:title>";
            PptxSceneChart chart = TestAssert.NotNull(PptxTests.BuildSingleChartScene($$"""
                <c:chartSpace xmlns:c="http://schemas.openxmlformats.org/drawingml/2006/chart"
                    xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"
                    xmlns:mc="http://schemas.openxmlformats.org/markup-compatibility/2006"
                    xmlns:c14="http://schemas.microsoft.com/office/drawing/2007/8/2/chart">
                  {{row.Selector}}
                  <c:chart>{{title}}<c:autoTitleDeleted val="0"/><c:plotArea><c:barChart><c:ser>
                    <c:tx><c:v>Series</c:v></c:tx><c:val><c:numLit><c:pt idx="0"><c:v>2</c:v></c:pt></c:numLit></c:val>
                  </c:ser></c:barChart></c:plotArea></c:chart>{{chartText}}
                </c:chartSpace>
                """));
            TestAssert.True(chart.Title.IsAutoGenerated, "Source precedence must retain inferred-title ownership.");
            TestAssert.True(Math.Abs(row.Expected - PptxSceneBuilder.ResolveChartTitleTextStyleOverride(chart).FontSize!.Value) < 1e-9,
                "An inferred title size must use title-local, chart-global, then built-in/default precedence.");
        }
    }

    private static string TextProperties(int? size) => size is null ? "" :
        $"<c:txPr><a:bodyPr/><a:lstStyle/><a:p><a:pPr><a:defRPr sz=\"{size}\"/></a:pPr></a:p></c:txPr>";
}
